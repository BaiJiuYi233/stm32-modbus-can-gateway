/**
  * @brief  This function handles SysTick Handler.
  * @param  None
  * @retval None
  */
/* 1ms 系统节拍：HAL_IncTick() 喂 HAL_GetTick()，xPortSysTickHandler() 喂 FreeRTOS 调度 */
void SysTick_Handler(void)
{
  HAL_IncTick();
  /* 判断FreeRTOS调度器是否已经启动 */
  if (xTaskGetSchedulerState() != taskSCHEDULER_NOT_STARTED)
  {
    xPortSysTickHandler();
  }
}

